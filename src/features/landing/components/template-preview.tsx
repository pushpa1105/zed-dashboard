import { ArrowUpRight, Eye, MonitorPlay, ShoppingBag } from 'lucide-react';
import { useState } from 'react';

import type { WorkspaceSummary } from '@/core/feature/workspace-catalog';
import { useTranslation } from '@/core/i18n/use-translation';
import { Link } from '@/core/router/router';
import { LayoutWireframe } from '@/core/theme/components/layout-wireframe';
import { cn } from '@/shared/lib/cn';
import { Button } from '@/shared/ui/button';

import { checkoutUrl, PRICE } from '../lib/store';
import { liveDemoHref, useTemplateText } from '../lib/templates';

/**
 * The template's screenshot in a browser frame. Screenshots are generated by
 * `scripts/capture-previews.mjs`; until one exists (or if it fails to load)
 * a drawing of the template's layout stands in for it.
 */
export function TemplatePreview({
  workspace,
  className,
  size = 'md',
}: {
  workspace: WorkspaceSummary;
  className?: string;
  size?: 'md' | 'lg';
}) {
  const [failed, setFailed] = useState(!workspace.preview);
  const text = useTemplateText()(workspace);
  const Icon = workspace.icon;

  return (
    <div
      className={cn(
        'overflow-hidden rounded-xl border bg-card shadow-sm ring-1 ring-foreground/[0.02]',
        className,
      )}
    >
      <div className="flex h-7 items-center gap-1.5 border-b bg-muted/50 px-3">
        <span className="size-2 rounded-full bg-muted-foreground/25" />
        <span className="size-2 rounded-full bg-muted-foreground/25" />
        <span className="size-2 rounded-full bg-muted-foreground/25" />
        <span className="mx-auto truncate rounded-md bg-background px-2 py-0.5 font-mono text-[0.625rem] text-muted-foreground">
          app.orbitly.io{workspace.basePath}
        </span>
      </div>
      <div className="relative aspect-[16/10] overflow-hidden bg-muted/40">
        {failed ? (
          <div className="relative size-full">
            <LayoutWireframe layout={workspace.layout} className="size-full opacity-90" />
            <div className="absolute inset-0 flex items-center justify-center">
              <span
                className={cn(
                  'flex items-center gap-2.5 rounded-xl border bg-card/95 px-3.5 py-2.5 shadow-sm backdrop-blur',
                  size === 'lg' && 'px-5 py-3.5',
                )}
              >
                <span className="flex size-8 items-center justify-center rounded-lg bg-primary text-primary-foreground">
                  <Icon className="size-4" />
                </span>
                <span className="text-sm font-semibold">{text.name}</span>
              </span>
            </div>
          </div>
        ) : (
          <img
            src={workspace.preview}
            alt={text.name}
            loading="lazy"
            decoding="async"
            onError={() => setFailed(true)}
            className="size-full object-cover object-top"
          />
        )}
      </div>
    </div>
  );
}

/** Gallery card: preview, name, category, layout tag, page count and the two actions. */
export function TemplateCard({
  workspace,
  onDetails,
  className,
}: {
  workspace: WorkspaceSummary;
  onDetails?: () => void;
  className?: string;
}) {
  const { t } = useTranslation('landing');
  const text = useTemplateText()(workspace);
  const buyUrl = checkoutUrl(workspace.id);

  return (
    <article className={cn('group flex flex-col gap-4', className)}>
      <button
        type="button"
        onClick={onDetails}
        className="block rounded-xl text-left outline-none focus-visible:ring-2 focus-visible:ring-ring/50"
        aria-label={t('templates.previewOf', { name: text.name })}
      >
        <TemplatePreview
          workspace={workspace}
          className="transition-[transform,box-shadow] duration-300 group-hover:-translate-y-1 group-hover:shadow-lg"
        />
      </button>
      <div className="flex items-start justify-between gap-4">
        <div className="min-w-0 space-y-1">
          <div className="flex flex-wrap items-center gap-2">
            <h3 className="font-semibold">{text.name}</h3>
            {text.category && (
              <span className="rounded-full bg-primary/10 px-2 py-0.5 text-[0.6875rem] font-medium text-primary">
                {text.category}
              </span>
            )}
          </div>
          <p className="line-clamp-1 text-sm text-muted-foreground">{text.description}</p>
          <p className="text-xs text-muted-foreground">
            {text.layout} · {text.pages}
          </p>
        </div>
      </div>
      <div className="mt-auto flex gap-2">
        <Button asChild size="sm" variant={buyUrl ? 'outline' : 'default'} className="flex-1">
          <Link to={liveDemoHref(workspace.basePath)}>
            <MonitorPlay /> {t('templates.livePreview')}
          </Link>
        </Button>
        {buyUrl ? (
          <Button asChild size="sm" className="flex-1">
            <a href={buyUrl}>
              <ShoppingBag /> {t('templates.store.buy', { price: PRICE.dashboard })}
            </a>
          </Button>
        ) : (
          onDetails && (
            <Button size="sm" variant="outline" className="flex-1" onClick={onDetails}>
              <Eye /> {t('templates.details')}
            </Button>
          )
        )}
      </div>
    </article>
  );
}

/** Small link used in hero CTAs. */
export function LiveDemoLink({ basePath, className }: { basePath: string; className?: string }) {
  const { t } = useTranslation('landing');
  return (
    <Link
      to={liveDemoHref(basePath)}
      className={cn(
        'inline-flex items-center gap-1 text-sm font-medium text-primary hover:underline',
        className,
      )}
    >
      {t('templates.heroCta')} <ArrowUpRight className="size-3.5" />
    </Link>
  );
}
